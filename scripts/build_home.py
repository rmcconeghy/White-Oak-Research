#!/usr/bin/env python3
"""Build the White Oak editorial homepage from the existing permanent essays."""
from datetime import date
from html import escape
from html.parser import HTMLParser
from pathlib import Path
import argparse
import re

from build_writing import EssayParser


class FirstParagraph(HTMLParser):
    """Capture the first non-metadata paragraph inside the permanent article."""
    def __init__(self, source):
        super().__init__(convert_charrefs=True)
        self.in_article = False
        self.in_paragraph = False
        self.skip = False
        self.parts = []
        self.paragraph = ""
        self.feed(source)

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == "article":
            self.in_article = True
        if self.in_article and tag == "p" and not self.paragraph and not self.in_paragraph:
            self.in_paragraph = True
            self.skip = "essay-meta" in attrs.get("class", "").split()
            self.parts = []

    def handle_data(self, data):
        if self.in_paragraph and not self.skip:
            self.parts.append(data)

    def handle_endtag(self, tag):
        if tag == "p" and self.in_paragraph:
            if not self.skip:
                text = " ".join(" ".join(self.parts).split())
                if text:
                    self.paragraph = text
            self.in_paragraph = False
            self.skip = False
        if tag == "article":
            self.in_article = False


def excerpt(article, limit=165):
    plain = FirstParagraph(article).paragraph
    plain = re.sub(r"https?://\S+", "", plain)
    plain = " ".join(plain.split()).strip(" ,;")
    if len(plain) > limit:
        plain = plain[:limit + 1].rsplit(" ", 1)[0].rstrip(" ,;:.") + "…"
    return plain


def build(root):
    root = Path(root)
    essays = []
    for path in sorted((root / "writing").glob("*/index.html")):
        source = path.read_text(encoding="utf-8")
        parsed = EssayParser(source)
        if parsed.attrs.get("data-status", "published") == "draft":
            continue
        if parsed.start is None or parsed.end is None or len(parsed.titles) != 1:
            raise ValueError(f"{path}: requires one article and one heading")
        published = date.fromisoformat(parsed.attrs.get("data-published", ""))
        if published.isoformat() not in parsed.times:
            raise ValueError(f"{path}: publication date and visible time differ")
        article = source[parsed.start:parsed.end]
        essays.append((published, path.parent.name, parsed.titles[0], excerpt(article)))
    if not essays:
        raise ValueError("No published essays found")
    essays.sort(key=lambda item: (item[0], item[1]), reverse=True)

    previews = []
    for i, (published, slug, title, summary) in enumerate(essays[:4]):
        latest = i == 0
        css = "essay-preview essay-preview--latest" if latest else "essay-preview"
        heading = escape(title)
        href = f"./writing/{escape(slug, quote=True)}/"
        date_label = f"{published:%B} {published.day}, {published.year}"
        previews.append(
            f'<article class="{css}">\n'
            f'  <time datetime="{published.isoformat()}">{date_label}</time>\n'
            f'  <h3><a href="{href}">{heading}</a></h3>\n'
            f'  <p>{escape(summary)}</p>\n'
            + (f'  <a class="card-action" href="{href}">Read the essay <span aria-hidden="true">↗</span></a>\n'
               if latest else "")
            + '</article>'
        )
    template = (root / "scripts/templates/home.html").read_text(encoding="utf-8")
    if template.count("{{ESSAY_PREVIEWS}}") != 1 or template.count("{{WRITING_COUNT}}") != 1:
        raise ValueError("Homepage template must contain one preview and one count placeholder")
    output = ('<!-- Generated by scripts/build_home.py; edit scripts/templates/home.html, not this file. -->\n'
              + template.replace("{{ESSAY_PREVIEWS}}", "\n".join(previews))
                        .replace("{{WRITING_COUNT}}", str(len(essays))))
    (root / "index.html").write_text(output, encoding="utf-8")
    return output


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    build(parser.parse_args().root)
