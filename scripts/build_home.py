#!/usr/bin/env python3
"""Generate compact homepage links from the same canonical essays as Writing."""
from datetime import date
from html import escape
from pathlib import Path
import argparse

from build_writing import EssayParser


def build(root):
    root = Path(root)
    essays = []
    for path in sorted((root / "writing").glob("*/index.html")):
        parsed = EssayParser(path.read_text(encoding="utf-8"))
        if parsed.attrs.get("data-status", "published") == "draft":
            continue
        if parsed.start is None or parsed.end is None or len(parsed.titles) != 1:
            raise ValueError(f"{path}: requires one article and one heading")
        published = date.fromisoformat(parsed.attrs.get("data-published", ""))
        if published.isoformat() not in parsed.times:
            raise ValueError(f"{path}: publication date and visible time differ")
        essays.append((published, path.parent.name, parsed.titles[0]))
    if not essays:
        raise ValueError("No published essays found")
    essays.sort(key=lambda item: (item[0], item[1]), reverse=True)

    previews = []
    for i, (published, slug, title) in enumerate(essays[:4]):
        latest = i == 0
        css = "essay-preview essay-preview--latest" if latest else "essay-preview"
        href = f"./writing/{escape(slug, quote=True)}/"
        date_label = f"{published:%B} {published.day}, {published.year}"
        previews.append(
            f'<article class="{css}">\n'
            f'  <time datetime="{published.isoformat()}">{date_label}</time>\n'
            f'  <h3><a href="{href}">{escape(title)}</a></h3>\n'
            + (f'  <a class="card-action" href="{href}">Read essay <span aria-hidden="true">↗</span></a>\n'
               if latest else "")
            + '</article>'
        )
    template = (root / "scripts/templates/home.html").read_text(encoding="utf-8")
    if template.count("{{ESSAY_PREVIEWS}}") != 1:
        raise ValueError("Homepage template must contain one essay preview placeholder")
    output = ('<!-- Generated by scripts/build_home.py; edit scripts/templates/home.html, not this file. -->\n'
              + template.replace("{{ESSAY_PREVIEWS}}", "\n".join(previews)))
    (root / "index.html").write_text(output, encoding="utf-8")
    return output


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    build(parser.parse_args().root)
